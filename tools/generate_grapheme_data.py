"""Generate the packed Unicode 17.0 grapheme properties used by zircon_text.

Pass a directory with GraphemeBreakProperty.txt, emoji-data.txt, and
DerivedCoreProperties.txt from https://www.unicode.org/Public/17.0.0/ucd/.
"""

import argparse
from pathlib import Path


def entries(path):
    for line in path.read_text(encoding="utf-8").splitlines():
        data = line.partition("#")[0].strip()
        if not data:
            continue
        points, *properties = map(str.strip, data.split(";"))
        first, _, last = points.partition("..")
        yield int(first, 16), int(last or first, 16), properties


def generate(data):
    classes = ("CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator",
               "Prepend", "SpacingMark", "L", "V", "T")
    values = bytearray(0x110000)
    for start, end, (kind,) in entries(data / "GraphemeBreakProperty.txt"):
        if kind not in ("LV", "LVT"):
            values[start:end + 1] = bytes([classes.index(kind) + 1]) * (end - start + 1)
    for start, end, (kind,) in entries(data / "emoji-data.txt"):
        if kind == "Extended_Pictographic":
            for point in range(start, end + 1):
                values[point] |= 0x10
    for start, end, properties in entries(data / "DerivedCoreProperties.txt"):
        if properties[0] == "InCB":
            bits = ("Consonant", "Extend", "Linker").index(properties[1]) + 1
            for point in range(start, end + 1):
                values[point] |= bits << 5

    print("// Generated by tools/generate_grapheme_data.py from Unicode 17.0.0.")
    print("// Unicode data license: unicode-license.txt.")
    print("pub const Range = struct { first: u21, last: u21, bits: u8 };")
    print("pub const ranges = [_]Range{")
    start = 0
    for point in range(1, len(values)):
        if values[point] != values[start]:
            if values[start]:
                print(f"    .{{ .first = 0x{start:x}, .last = 0x{point - 1:x}, .bits = 0x{values[start]:x} }},")
            start = point
    assert values[start] == 0
    print("};")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("data", type=Path)
    generate(parser.parse_args().data)
